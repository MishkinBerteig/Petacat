def quality_phrase(quality: float, templates: dict[str, Any]) -> str:
    """Scheme: ``answer-quality-phrase`` (``answers.ss:95-105``)."""
    for entry in (templates or {}).get("answer_quality_phrases", []):
        maximum = entry.get("max_quality")
        if maximum is None or quality < maximum:
            return entry.get("phrase", "")
    return ""


def coherence_phrase(coherence: float, templates: dict[str, Any]) -> str:
    """Scheme: ``coherence-phrase`` (``answers.ss:919-926``).

    The bands fix what the argument means.  ``answer-incoherent?``
    (``answers.ss:909-916``) declares an answer incoherent once its rule is more than 25
    points more literal than its themes, which falls inside this table's "incoherent"
    band when coherence is read as *rule abstractness minus theme abstractness*.
    :func:`coherence_score` computes it that way, and ``explain`` reports the phrase
    alongside the boolean.
    """
    for entry in (templates or {}).get("coherence_phrases", []):
        maximum = entry.get("max_coherence")
        if maximum is None or coherence < maximum:
            return entry.get("phrase", "")
    return ""


def coherence_score(answer: AnswerDescription) -> float:
    """How far the answer's rule sits below its themes in abstractness.

    Negative means the dissonance §4.7.3 describes for ``dyz``: "themes based on the
    abstract concept of opposite, but ... a literal-minded interpretation of abc => abd".
    """
    return float(answer.top_rule_abstractness) - float(answer.theme_abstractness)


