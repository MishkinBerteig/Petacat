"""Talking about answers — MetaCat's explanations and comparisons, in English.

Scheme source: ``answers.ss:310-333`` (``explain``), ``answers.ss:336-425``
(``theme-phrases``) and ``answers.ss:434-882`` (``get-answer-comparison-text``).

§4.7.4 is explicit that none of this is linguistic competence: "the program possesses
no genuine linguistic ability whatsoever; its ability to 'speak' is purely an illusion
arising from a flexible set of phrase-templates".  The templates are therefore *data*,
and in this port they live in ``seed_data/commentary_templates.json`` — every phrase in
this module comes from there, and nothing here writes English down in Python.  Editing
the seed data (or the admin UI, which edits the same row) changes what the program says.

Two facts about the shape of the output are worth stating before the code:

* **The comparison has one voice, not two.**  §4.6 footnote 16: "Turning off Eliza mode
  ... does not affect the commentary generated by the program when comparing different
  answers."  ``compare-answers`` (``answers.ss:428-431``) passes the *same* string as
  both the Eliza and the technical paragraph.  ``explain`` (``answers.ss:326-333``) does
  differ between voices, but only in its last sentence, and the two remain isomorphic —
  one paragraph either way, which is the property §4.6 stresses at pp. 183-184.
* **The prose is one paragraph.**  ``get-answer-comparison-text`` returns a single
  ``string-append``.  This module keeps its seven segments (the opening contrast, the two
  unique-theme sentences, the rule difference, the two incoherence remarks and the
  verdict) so a UI can lay them out, and ``text`` re-joins them with the leading spaces
  the Scheme itself emits, making the joined string the paragraph MetaCat prints.
"""

from __future__ import annotations

from functools import lru_cache
from typing import TYPE_CHECKING, Any

if TYPE_CHECKING:
    from server.engine.memory import AnswerDescription, EpisodicMemory

# A theme as this module handles it: (dimension, relation), matching the Scheme's
# ``(<slipnode> <relation>)`` theme-pattern entries.
Theme = tuple[str, str]

# The five theme dimensions ``theme-phrases`` knows how to talk about
# (``answers.ss:340-344``).  Direction is looked up nowhere: the Scheme's own comment at
# ``answers.ss:341`` says "Direction-theme should always be the same as StringPos-theme",
# and the String-Position phrase carries the direction wording for both.
STRING_POSITION = "plato-string-position-category"
ALPHABETIC_POSITION = "plato-alphabetic-position-category"
GROUP_CATEGORY = "plato-group-category"
BOND_FACET = "plato-bond-facet"
DIRECTION = "plato-direction-category"

#: Order of the verdict criteria when the seed data does not supply one.  It is the
#: order of the ``cond`` at ``answers.ss:824-882``, and the seed data's
#: ``comparison_judgment_priority`` says the same thing.
DEFAULT_JUDGMENT_PRIORITY = (
    "both_incoherent",
    "one_incoherent_other_not",
    "fewer_unjustified_themes",
    "more_abstract_rule",
    "richer_set_of_ideas",
    "neither_better",
)


# ---------------------------------------------------------------------------
# Template plumbing
# ---------------------------------------------------------------------------


def _fill(template: str, **values: Any) -> str:
    """Substitute ``{name}`` placeholders, leaving unknown ones alone.

    The templates are user-editable through the admin UI, so substitution is tolerant:
    a brace this call has no value for stays in the text and the rest of the phrase
    still renders.
    """
    text = template
    for key, value in values.items():
        text = text.replace("{" + key + "}", "" if value is None else str(value))
    return text


def resolve_templates(templates: dict[str, Any] | None) -> dict[str, Any]:
    """Whatever the caller supplied, or the seed data if it supplied nothing.

    Served requests pass ``meta.commentary_templates``, which came from Postgres, so an
    admin edit takes effect on the next comparison.  ``None`` is for callers with no
    ``MetadataProvider``.
    """
    if templates:
        return templates
    from server.engine.metadata import default_commentary_templates

    return default_commentary_templates()


def _section(templates: dict[str, Any], *path: str) -> Any:
    """Walk into the template tree, returning ``{}`` for anything absent."""
    node: Any = templates or {}
    for key in path:
        if not isinstance(node, dict):
            return {}
        node = node.get(key, {})
    return node


def _text(templates: dict[str, Any], *path: str) -> str:
    value = _section(templates, *path)
    return value if isinstance(value, str) else ""


def punctuate_with_commas(conj: str, parts: list[str]) -> str:
    """Scheme: ``punctuate-with-commas`` (``answers.ss:267-276``).

    The comma stands before the conjunction even in the two-item case: "a, and b".
    """
    parts = [p for p in parts if p]
    if not parts:
        return ""
    if len(parts) == 1:
        return parts[0]
    if len(parts) == 2:
        return f"{parts[0]}, {conj} {parts[1]}"
    return "".join(f"{p}, " for p in parts[:-1]) + f"{conj} {parts[-1]}"


# ---------------------------------------------------------------------------
# Themes on an answer description
# ---------------------------------------------------------------------------


def themes_of(answer: AnswerDescription) -> list[Theme]:
    return list(answer.themes.items())


def unjustified_of(answer: AnswerDescription) -> list[Theme]:
    return list(answer.unjustified_themes.items())


def all_themes_of(answer: AnswerDescription) -> list[Theme]:
    """``(append (get-themes) (get-unjustified-themes))`` — ``answers.ss:456-464``.

    The two patterns are separate dicts keyed by dimension, so an entry can occur in
    both; each distinct ``(dimension, relation)`` pair contributes one theme.  The
    length of this list is what "a richer set of ideas" is measured on
    (``answers.ss:876-881``).
    """
    justified = themes_of(answer)
    return justified + [t for t in unjustified_of(answer) if t not in justified]


def _lookup(dimension: str, themes: list[Theme]) -> Theme | None:
    """``assq`` over a theme list: the *first* entry for the dimension wins."""
    for theme in themes:
        if theme[0] == dimension:
            return theme
    return None


def snag_explanation_for(
    answer: AnswerDescription,
    memory: EpisodicMemory | None,
    templates: dict[str, Any],
) -> str:
    """Scheme: ``get-snag-explanation`` (``answers.ss:302-307``).

    The sentence is rebuilt from what a ``SnagDescription`` stores — the rule and the
    target string — through ``caveat_templates.snag_explanation``, the same template the
    snag commentary uses, so the caveat quotes the wording the user saw when the snag
    happened.
    """
    snag = memory.get_equivalent_snag(answer) if memory is not None else None
    if snag is None:
        return ""
    return _fill(
        _text(templates, "caveat_templates", "snag_explanation"),
        rule=snag.description,
        target=snag.problem[2] if len(snag.problem) > 2 else "",
    )


def snag_justified_themes(
    answer: AnswerDescription, memory: EpisodicMemory | None
) -> list[Theme]:
    """Scheme: ``get-snag-justified-themes`` (``answers.ss:285-299``).

    §4.7.3: an unjustified theme is reclassified as snag-justified when the program has
    hit a snag on the very same strings and rule, because then "the differences between
    the themes involved in the snag and the themes involved in the answer provide a
    strong clue as to how ... the snag is avoided".  So the themes that count are the
    answer's themes *minus the snag's own* — the ones the snag episode did not have —
    intersected with the unjustified ones.
    """
    if memory is None:
        return []
    snag = memory.get_equivalent_snag(answer)
    if snag is None:
        return []
    snag_themes = list((snag.theme_pattern or {}).items())
    unjustified = unjustified_of(answer)
    avoiding = [t for t in all_themes_of(answer) if t not in snag_themes]
    return [t for t in avoiding if t in unjustified]


# ---------------------------------------------------------------------------
# theme-phrases  (answers.ss:336-425)
# ---------------------------------------------------------------------------


def theme_phrases(
    templates: dict[str, Any],
    *,
    prep: str,
    conj: str,
    ending: str,
    themes: list[Theme],
    snag_justified_themes: list[Theme],
    unjustified_themes: list[Theme],
    initial: str | None,
    target: str | None,
    snag_explanation: str = "",
    add_caveats: bool = False,
    the_strings: bool = False,
    two_strings: str | None = None,
) -> str:
    """Describe a set of themes as one English clause.

    A direct port of ``theme-phrases`` (``answers.ss:336-425``), including its ordering:
    String-Position (carrying Group-Category and direction), Group-Category on its own,
    Bond-Facet, Alphabetic-Position — joined by ``punctuate-with-commas``.

    The dissertation walks through exactly this function at §4.7.4 pp. 194-195, where
    slots 1 and 2 of "⟨1⟩ see⟨2⟩ ⟨3⟩ as ⟨4⟩ ⟨5⟩ ⟨6⟩" are the ``prep`` and ``ending``
    arguments that make "on seeing" or "of seeing" or "to see" as the context demands.
    """
    tpl = _section(templates, "theme_phrase_templates")
    all_themes = list(themes) + list(unjustified_themes)

    if two_strings is not None:
        strings = _fill(_text(tpl, "strings", "two_strings"), two_strings=two_strings)
    else:
        strings = _fill(
            _text(tpl, "strings", "pair"), initial=initial, target=target
        )
    the_strings_phrase = _text(tpl, "strings", "the_strings")

    caveats = _section(templates, "caveat_templates")

    def caveat(theme: Theme) -> str:
        if not add_caveats:
            return ""
        if theme in unjustified_themes:
            return _text(templates, "caveat_templates", "unjustified")
        if theme in snag_justified_themes:
            return _fill(
                caveats.get("snag_justified", ""),
                snag_explanation=snag_explanation,
            )
        return ""

    string_position = _lookup(STRING_POSITION, all_themes)
    group_category = _lookup(GROUP_CATEGORY, all_themes)
    bond_facet = _lookup(BOND_FACET, all_themes)
    alphabetic = _lookup(ALPHABETIC_POSITION, all_themes)

    # An unjustified Group-Category theme is not mentioned as a qualifier
    # (``answers.ss:366-368``): the program will not assert an idea it cannot back up.
    group_category_usable = group_category is not None and (
        group_category not in unjustified_themes
    )

    parts: list[str] = []

    if string_position is not None:
        section = _section(tpl, "string_position")
        qualifier = ""
        if group_category_usable:
            qualifier = _section(section, "group_qualifier").get(
                group_category[1], ""
            )
        parts.append(
            _fill(
                section.get("template", ""),
                prep=prep,
                ending=ending,
                strings=strings,
                group_qualifier=qualifier,
                direction=_section(section, "direction").get(string_position[1], ""),
                caveat=caveat(string_position),
            )
        )

    if group_category is not None and string_position is None and group_category_usable:
        section = _section(tpl, "group_category_standalone")
        parts.append(
            _fill(
                section.get("template", ""),
                prep=prep,
                ending=ending,
                strings=strings,
                group_category=_section(section, "group_category").get(
                    group_category[1], ""
                ),
                bond_facet_clause=(
                    section.get("bond_facet_clause", "")
                    if bond_facet is not None
                    else ""
                ),
                caveat=caveat(group_category),
            )
        )

    # ``answers.ss:403-406``: Bond-Facet gets its own clause unless the Group-Category
    # clause above already carried it.
    if bond_facet is not None and (
        string_position is not None or not group_category_usable
    ):
        parts.append(
            _fill(
                _text(tpl, "bond_facet", "template"),
                prep=prep,
                ending=ending,
                strings=(
                    the_strings_phrase
                    if (string_position is not None or the_strings)
                    else strings
                ),
                caveat=caveat(bond_facet),
            )
        )

    if alphabetic is not None:
        section = _section(tpl, "alphabetic_position")
        parts.append(
            _fill(
                section.get("template", ""),
                prep=prep,
                ending=ending,
                relation=_section(section, "relation").get(alphabetic[1], ""),
                strings=(
                    the_strings_phrase
                    if (string_position is not None or the_strings)
                    else strings
                ),
                caveat=caveat(alphabetic),
            )
        )

    return punctuate_with_commas(conj, parts)


