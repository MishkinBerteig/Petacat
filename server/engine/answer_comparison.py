def compare_answers_text(
    answer_a: AnswerDescription,
    answer_b: AnswerDescription,
    memory: EpisodicMemory | None = None,
    templates: dict[str, Any] | None = None,
    meta: Any = None,
) -> dict[str, Any]:
    """The full comparison paragraph for two answers.

    A port of ``get-answer-comparison-text`` (``answers.ss:434-882``).  The classification
    it works from — common, differing and unique themes, unjustified and snag-justified
    themes, and the two rules — is §4.7.3's, and the phrase-templates it fills are
    §4.7.4's.  What comes out is one paragraph; the segments are returned separately only
    so a UI can break it up.
    """
    ctx = AnswerComparison(answer_a, answer_b, memory, templates, meta)
    return ctx.render()


class AnswerComparison:
    """The ``let*`` block of ``get-answer-comparison-text``, kept in one place.

    The Scheme binds some fifty intermediate values before its first ``string-append``,
    and they are interdependent: the verdict needs the theme classification, and the
    unique-theme sentences need to know which answer was mentioned first.  They are
    computed once in ``__init__`` and read by the segment methods.
    """

    def __init__(
        self,
        self_answer: AnswerDescription,
        other_answer: AnswerDescription,
        memory: EpisodicMemory | None = None,
        templates: dict[str, Any] | None = None,
        meta: Any = None,
    ) -> None:
        templates = resolve_templates(templates)
        self.templates = templates
        self.meta = meta
        self.memory = memory
        self.a = self_answer
        self.b = other_answer
        cmp_tpl = _section(templates, "comparison_templates")
        self.tpl = cmp_tpl

        self.initial1, self.modified1, self.target1, self.answer1 = self_answer.problem
        self.initial2, self.modified2, self.target2, self.answer2 = other_answer.problem

        self.problem1 = _fill(
            cmp_tpl.get("problem", ""),
            initial=self.initial1,
            modified=self.modified1,
            target=self.target1,
        )
        self.problem2 = _fill(
            cmp_tpl.get("problem", ""),
            initial=self.initial2,
            modified=self.modified2,
            target=self.target2,
        )
        self.change1 = _fill(
            cmp_tpl.get("change", ""), initial=self.initial1, modified=self.modified1
        )
        self.change2 = _fill(
            cmp_tpl.get("change", ""), initial=self.initial2, modified=self.modified2
        )
        self.full_answer1 = _fill(
            cmp_tpl.get("full_answer", ""), answer=self.answer1, problem=self.problem1
        )
        self.full_answer2 = _fill(
            cmp_tpl.get("full_answer", ""), answer=self.answer2, problem=self.problem2
        )
        # ``answers.ss:450-451``: an answer is named with its problem on first mention,
        # and by name alone once both answers belong to the same problem.
        same_problem = self.problem1 == self.problem2
        self.answer1_phrase = self.answer1 if same_problem else self.full_answer1
        self.answer2_phrase = self.answer2 if same_problem else self.full_answer2

        # ---- theme classification (answers.ss:455-543) ----
        self.all_themes1 = all_themes_of(self_answer)
        self.all_themes2 = all_themes_of(other_answer)
        self.snag_justified1 = snag_justified_themes(self_answer, memory)
        self.snag_justified2 = snag_justified_themes(other_answer, memory)
        self.unjustified1 = [
            t for t in unjustified_of(self_answer) if t not in self.snag_justified1
        ]
        self.unjustified2 = [
            t for t in unjustified_of(other_answer) if t not in self.snag_justified2
        ]
        self.all_unjustified = list(self.unjustified1)
        self.all_unjustified += [
            t for t in self.unjustified2 if t not in self.all_unjustified
        ]
        self.snag_explanation1 = snag_explanation_for(self_answer, memory, templates)
        self.snag_explanation2 = snag_explanation_for(other_answer, memory, templates)

        self.common_themes = [t for t in self.all_themes1 if t in self.all_themes2]
        common_dimensions = {d for d, _ in self.common_themes}
        dimensions1 = [d for d, _ in self.all_themes1]
        dimensions2 = {d for d, _ in self.all_themes2}
        self.differing_dimensions = [
            d
            for d in dict.fromkeys(dimensions1)
            if d in dimensions2 and d not in common_dimensions
        ]
        self.answer1_only = [t for t in self.all_themes1 if t not in self.common_themes]
        self.answer2_only = [t for t in self.all_themes2 if t not in self.common_themes]
        self.differing1 = [
            t for t in self.all_themes1 if t[0] in self.differing_dimensions
        ]
        self.differing2 = [
            t for t in self.all_themes2 if t[0] in self.differing_dimensions
        ]
        self.unique1 = [t for t in self.answer1_only if t not in self.differing1]
        self.unique2 = [t for t in self.answer2_only if t not in self.differing2]

        common_unjustified = [t for t in self.unjustified1 if t in self.unjustified2]
        self.common_a_only_unjustified = [
            t
            for t in self.unjustified1
            if t not in common_unjustified and t not in self.differing1
        ]
        self.common_b_only_unjustified = [
            t
            for t in self.unjustified2
            if t not in common_unjustified and t not in self.differing2
        ]
        self.justification_differences = bool(
            self.common_a_only_unjustified or self.common_b_only_unjustified
        )

        self.num_theme_differences = (
            len(self.differing_dimensions) + len(self.unique1) + len(self.unique2)
        )
        self.theme_differences = self.num_theme_differences != 0

        # ---- rule comparison (answers.ss:597-620) ----
        self.rule_differences = compare_rule_signatures(
            self_answer.top_rule_signature, other_answer.top_rule_signature
        )
        self.num_rule_differences = count_rule_differences(self.rule_differences, meta)
        self.rule_differences_exist = self.num_rule_differences != 0
        rule_tpl = _section(cmp_tpl, "rule_explanation")
        if self.rule_differences is None:
            self.rule_difference_phrase = rule_tpl.get(
                "phrase_completely_different", ""
            )
        else:
            delta = (
                self_answer.top_rule_abstractness - other_answer.top_rule_abstractness
            )
            if delta > 0:
                self.rule_difference_phrase = rule_tpl.get("phrase_more_abstract", "")
            elif delta < 0:
                self.rule_difference_phrase = rule_tpl.get("phrase_more_literal", "")
            else:
                self.rule_difference_phrase = rule_tpl.get(
                    "phrase_somewhat_different", ""
                )

        # ``answers.ss:621-637``: in the one branch where the second answer is named
        # first, two answers that spell the same have to swap "first" and "second".
        self.b_mentioned_first = self.theme_differences and not self.answer1_only
        self.order1 = "second" if self.b_mentioned_first else "first"
        self.order2 = "first" if self.b_mentioned_first else "second"
        same_string = self.answer1 == self.answer2
        self.same_string = same_string
        ordinal = cmp_tpl.get("answer_ordinal", "")
        self.answer1_ref = (
            _fill(ordinal, order=self.order1, answer=self.answer1)
            if same_string
            else self.answer1
        )
        self.answer2_ref = (
            _fill(ordinal, order=self.order2, answer=self.answer2)
            if same_string
            else self.answer2
        )

    # -- reusable clauses ---------------------------------------------------

    def _similarities(self, with_caveats: bool) -> str:
        """``similarities`` (``answers.ss:659-669``) — what both answers rely on."""
        section = _section(self.tpl, "no_theme_differences")
        if self.initial1 == self.initial2 and self.target1 == self.target2:
            two_strings = _fill(
                section.get("similarity_strings_same_problem", ""),
                initial=self.initial1,
                target=self.target1,
            )
        else:
            two_strings = _fill(
                section.get("similarity_strings_different_problems", ""),
                initial1=self.initial1,
                target1=self.target1,
                initial2=self.initial2,
                target2=self.target2,
            )
        return _fill(
            section.get("similarities", ""),
            theme_phrases=theme_phrases(
                self.templates,
                prep="on ",
                conj="and",
                ending="ing",
                themes=self.common_themes,
                snag_justified_themes=[],
                unjustified_themes=self.all_unjustified,
                initial=None,
                target=None,
                add_caveats=with_caveats,
                the_strings=False,
                two_strings=two_strings,
            ),
        )

    def _no_justification(self, first: bool) -> str:
        """``no-justification1`` / ``no-justification2`` (``answers.ss:549-590``)."""
        section = _section(self.tpl, "no_theme_differences")
        if first:
            themes = self.common_a_only_unjustified
            snag_justified, unjustified = self.snag_justified1, self.unjustified1
            initial, target = self.initial1, self.target1
            other_initial, other_target = self.initial2, self.target2
            other_snag_justified = self.snag_justified2
            other_snag_explanation = self.snag_explanation2
            key = "no_justification_former"
        else:
            themes = self.common_b_only_unjustified
            snag_justified, unjustified = self.snag_justified2, self.unjustified2
            initial, target = self.initial2, self.target2
            other_initial, other_target = self.initial1, self.target1
            other_snag_justified = self.snag_justified1
            other_snag_explanation = self.snag_explanation1
            key = "no_justification_latter"

        shared_with_other_snag = [t for t in themes if t in other_snag_justified]
        snag_clause = ""
        if shared_with_other_snag:
            snag_clause = _fill(
                section.get("no_justification_snag_clause", ""),
                theme_phrases=theme_phrases(
                    self.templates,
                    prep="",
                    conj="and",
                    ending="ing",
                    themes=shared_with_other_snag,
                    snag_justified_themes=[],
                    unjustified_themes=shared_with_other_snag,
                    initial=other_initial,
                    target=other_target,
                    the_strings=True,
                ),
                snag_explanation=other_snag_explanation,
            )
        return _fill(
            section.get(key, ""),
            theme_phrases=theme_phrases(
                self.templates,
                prep="to ",
                conj="or",
                ending="",
                themes=themes,
                snag_justified_themes=snag_justified,
                unjustified_themes=unjustified,
                initial=initial,
                target=target,
                the_strings=True,
            ),
            initial=other_initial,
            target=other_target,
            snag_clause=snag_clause,
        )

    def _rule_explanation(self, intro: str, subject: str) -> str:
        """``rule-explanation-template`` (``answers.ss:638-652``)."""
        section = _section(self.tpl, "rule_explanation")
        if self.same_string:
            answer1 = _fill(section.get("answer1_ordinal", ""), order=self.order1)
            answer2 = _fill(section.get("answer2_ordinal", ""), order=self.order2)
        else:
            answer1 = _fill(section.get("answer1_named", ""), answer=self.answer1)
            answer2 = _fill(section.get("answer2_named", ""), answer=self.answer2)
        change2 = (
            section.get("change2_same", "")
            if self.change1 == self.change2
            else _fill(section.get("change2_different", ""), change2=self.change2)
        )
        return _fill(
            section.get("template", ""),
            intro=intro,
            subject=subject,
            change1=self.change1,
            rule_difference_phrase=self.rule_difference_phrase,
            answer1=answer1,
            change2=change2,
            answer2=answer2,
        )

    def _answer_theme_phrases(self, first: bool, themes: list[Theme]) -> str:
        if first:
            return theme_phrases(
                self.templates,
                prep="on ",
                conj="and",
                ending="ing",
                themes=themes,
                snag_justified_themes=self.snag_justified1,
                unjustified_themes=self.unjustified1,
                initial=self.initial1,
                target=self.target1,
                snag_explanation=self.snag_explanation1,
                add_caveats=True,
            )
        return theme_phrases(
            self.templates,
            prep="on ",
            conj="and",
            ending="ing",
            themes=themes,
            snag_justified_themes=self.snag_justified2,
            unjustified_themes=self.unjustified2,
            initial=self.initial2,
            target=self.target2,
            snag_explanation=self.snag_explanation2,
            add_caveats=True,
        )

    # -- segments -----------------------------------------------------------

    def _opening(self) -> str:
        no_diff = _section(self.tpl, "no_theme_differences")
        diff = _section(self.tpl, "theme_differences")
        in_part = diff.get("in_part", "")

        if not self.theme_differences:
            if not self.rule_differences_exist and not self.justification_differences:
                if self.change1 == self.change2:
                    sameness = _fill(
                        no_diff.get("rule_sameness_same_change", ""),
                        change1=self.change1,
                    )
                else:
                    sameness = _fill(
                        no_diff.get("rule_sameness_different_change", ""),
                        change1=self.change1,
                        change2=self.change2,
                    )
                return _fill(
                    no_diff.get("essentially_same", ""),
                    answer1=self.answer1_phrase,
                    answer2=self.full_answer2,
                    similarities=self._similarities(True),
                    rule_sameness=sameness,
                )
            if not self.justification_differences:
                both = _fill(
                    self.tpl.get("both_answers", ""),
                    answer1=self.answer1_phrase,
                    answer2=self.full_answer2,
                )
                return _fill(
                    no_diff.get("rule_differences_only", ""),
                    rule_explanation=self._rule_explanation(
                        _text(self.tpl, "rule_explanation", "intro_only_essential"),
                        both,
                    ),
                    similarities=self._similarities(True),
                )
            if not self.common_a_only_unjustified:
                return _fill(
                    no_diff.get("justification_differences", ""),
                    answer1=self.answer1_phrase,
                    answer2=self.full_answer2,
                    similarities=self._similarities(False),
                    no_justification=self._no_justification(False),
                )
            if not self.common_b_only_unjustified:
                return _fill(
                    no_diff.get("justification_differences", ""),
                    answer1=self.answer1_phrase,
                    answer2=self.full_answer2,
                    similarities=self._similarities(False),
                    no_justification=self._no_justification(True),
                )
            return _fill(
                no_diff.get("justification_differences_both", ""),
                answer1=self.answer1_phrase,
                answer2=self.full_answer2,
                similarities=self._similarities(False),
                no_justification1=self._no_justification(True),
                no_justification2=self._no_justification(False),
            )

        # Theme differences.
        if not self.answer1_only:
            return _fill(
                diff.get("one_answer", ""),
                answer=self.full_answer2,
                in_part=in_part if self.common_themes else "",
                theme_phrases=self._answer_theme_phrases(False, self.answer2_only),
            )
        if not self.answer2_only:
            return _fill(
                diff.get("one_answer", ""),
                answer=self.full_answer1,
                in_part=in_part if self.common_themes else "",
                theme_phrases=self._answer_theme_phrases(True, self.answer1_only),
            )
        return _fill(
            diff.get("both_answers", ""),
            answer1=self.full_answer1,
            in_part1=in_part if self.common_themes else "",
            theme_phrases1=self._answer_theme_phrases(True, self.answer1_only),
            answer2=self.answer2_phrase,
            in_part2=in_part if self.common_themes else "",
            theme_phrases2=self._answer_theme_phrases(False, self.answer2_only),
        )

    def _unique_sentence(self, first: bool) -> str:
        """``answers.ss:736-762`` — "In xyd's case, the idea ... does not arise."."""
        section = _section(self.tpl, "unique_theme")
        if first:
            themes = self.unique1
            if not themes:
                return ""
            contrast = not self.answer1_only or not self.answer2_only
            unmentioned = not self.answer2_only
            case_answer = self.answer2_phrase if unmentioned else self.answer2_ref
            snag_justified, unjustified = self.snag_justified1, self.unjustified1
            initial, target = self.initial2, self.target2
        else:
            themes = self.unique2
            if not themes:
                return ""
            contrast = (not self.answer1_only or not self.answer2_only) and (
                not self.unique1
            )
            unmentioned = not self.answer1_only
            case_answer = self.answer1_phrase if unmentioned else self.answer1_ref
            snag_justified, unjustified = self.snag_justified2, self.unjustified2
            initial, target = self.initial1, self.target1

        case = (
            _fill(section.get("case_named", ""), answer=case_answer)
            if unmentioned
            else _fill(section.get("case_possessive", ""), answer=case_answer)
        )
        return _fill(
            section.get("template", ""),
            intro=section.get(
                "intro_contrast" if contrast else "intro_plain", ""
            ),
            case=case,
            # ``answers.ss:745`` describes the theme with "of seeing", and against the
            # *other* answer's strings — it is that answer's case being described.
            theme_phrases=theme_phrases(
                self.templates,
                prep="of ",
                conj="and",
                ending="ing",
                themes=themes,
                snag_justified_themes=snag_justified,
                unjustified_themes=unjustified,
                initial=initial,
                target=target,
            ),
        )

    def _rule_sentence(self) -> str:
        if not self.rule_differences_exist:
            return ""
        if not self.theme_differences and not self.justification_differences:
            # Already said in the opening sentence.
            return ""
        section = _section(self.tpl, "rule_explanation")
        subject = (
            _fill(section.get("subject_two_identical_answers", ""), answer=self.answer1)
            if self.same_string
            else section.get("subject_the_answers", "")
        )
        return self._rule_explanation(section.get("intro_another_key", ""), subject)

    def _incoherence(self, first: bool, after_first: bool) -> str:
        """``answers.ss:772-805`` — the "seems incoherent to me" remark."""
        section = _section(self.tpl, "incoherence")
        if first:
            answer, themes = self.answer1, self.all_themes1
            initial, target, change = self.initial1, self.target1, self.change1
            snag_justified, unjustified = self.snag_justified1, self.unjustified1
            key = "first"
        else:
            answer, themes = self.answer2, self.all_themes2
            initial, target, change = self.initial2, self.target2, self.change2
            snag_justified, unjustified = self.snag_justified2, self.unjustified2
            key = "second_after_first" if after_first else "second_alone"
        similarity = section.get(
            "similarity_plural" if len(themes) > 1 else "similarity_singular", ""
        )
        return _fill(
            section.get(key, ""),
            answer=answer,
            similarity=similarity,
            initial=initial,
            target=target,
            change=change,
            theme_phrases=theme_phrases(
                self.templates,
                prep="",
                conj="and",
                ending="ing",
                themes=themes,
                snag_justified_themes=snag_justified,
                unjustified_themes=unjustified,
                initial=initial,
                target=target,
            ),
        )

    # -- the verdict (answers.ss:806-882) -----------------------------------

    def verdict(self) -> dict[str, Any]:
        """Which answer the program prefers, in the seed data's priority order.

        The order is ``comparison_judgment_priority``, which is MetaCat's ``cond`` at
        ``answers.ss:824-882`` written down as data.  Reordering that list reorders the
        judgement — which is the point of it being data.
        """
        section = _section(self.tpl, "verdict")
        priority = (self.templates or {}).get("comparison_judgment_priority") or list(
            DEFAULT_JUDGMENT_PRIORITY
        )
        for criterion in priority:
            handler = _CRITERIA.get(criterion)
            if handler is None:
                continue
            outcome = handler(self, section)
            if outcome is not None:
                outcome["criterion"] = criterion
                return outcome
        return _neither_better(self, section, section.get("intro_all_in_all", ""))

    def _better(
        self, section: dict[str, Any], first: bool, intro: str, reason: str
    ) -> dict[str, Any]:
        answer_ref = self.answer1_ref if first else self.answer2_ref
        return {
            "text": _fill(
                section.get("better", ""),
                intro=intro,
                answer=answer_ref,
                reason=reason,
            ),
            "answer": self.answer1 if first else self.answer2,
            "answer_ref": answer_ref,
        }

    # -- assembly -----------------------------------------------------------

    def render(self) -> dict[str, Any]:
        a_incoherent = not self.a.is_coherent
        b_incoherent = not self.b.is_coherent
        verdict = self.verdict()

        segments = [
            self._opening(),
            self._unique_sentence(True),
            self._unique_sentence(False),
            self._rule_sentence(),
            self._incoherence(True, False) if a_incoherent else "",
            self._incoherence(False, a_incoherent) if b_incoherent else "",
            verdict["text"],
        ]
        text = "".join(segments)
        paragraphs = [segment.strip() for segment in segments if segment.strip()]
        return {
            "text": text,
            "paragraphs": paragraphs,
            "segments": segments,
            "verdict": verdict["text"].strip(),
            # §4.6 footnote 16: comparison commentary is identical in both voices.
            "eliza_text": text,
            "technical_text": text,
            "preferred": {
                "answer": verdict.get("answer"),
                "reason": verdict.get("criterion", ""),
            },
        }


# ---------------------------------------------------------------------------
# The verdict criteria, one function each, named as the seed data names them
# ---------------------------------------------------------------------------


def _neither_better(
    ctx: AnswerComparison, section: dict[str, Any], intro: str
) -> dict[str, Any]:
    """``neither-better`` (``answers.ss:814-823``)."""
    phrase1 = quality_phrase(ctx.a.quality, ctx.templates)
    phrase2 = quality_phrase(ctx.b.quality, ctx.templates)
    if phrase1 == phrase2:
        text = _fill(
            section.get("both_same_quality", ""), intro=intro, quality_phrase=phrase1
        )
    else:
        text = _fill(
            section.get("different_quality", ""),
            intro=intro,
            answer1=ctx.answer1_ref,
            quality1=phrase1,
            answer2=ctx.answer2_ref,
            quality2=phrase2,
        )
    return {"text": text, "answer": None, "answer_ref": None}


def _criterion_both_incoherent(
    ctx: AnswerComparison, section: dict[str, Any]
) -> dict[str, Any] | None:
    """``answers.ss:825-841``: when neither answer hangs together, prefer the one that
    hangs together *less badly* — fewer abstract themes stranded above a literal rule."""
    if ctx.a.is_coherent or ctx.b.is_coherent:
        return None
    abstractness1 = ctx.a.theme_abstractness
    abstractness2 = ctx.b.theme_abstractness
    count1, count2 = len(ctx.all_themes1), len(ctx.all_themes2)
    intro = section.get("intro_overall", "")
    if (abstractness1 < abstractness2 and count1 <= count2) or (
        count1 < count2 and abstractness1 <= abstractness2
    ):
        return ctx._better(
            section,
            True,
            intro,
            _fill(section.get("reason_less_incoherent", ""), other=ctx.answer2_ref),
        )
    if (abstractness2 < abstractness1 and count2 <= count1) or (
        count2 < count1 and abstractness2 <= abstractness1
    ):
        return ctx._better(
            section,
            False,
            intro,
            _fill(section.get("reason_less_incoherent", ""), other=ctx.answer1_ref),
        )
    return _neither_better(ctx, section, section.get("intro_all_in_all", ""))


def _criterion_one_incoherent(
    ctx: AnswerComparison, section: dict[str, Any]
) -> dict[str, Any] | None:
    """``answers.ss:842-847``: the §4.7.4 worked example — xyd beats dyz "since it is
    more coherent"."""
    intro = section.get("intro_all_in_all", "")
    reason = section.get("reason_more_coherent", "")
    if ctx.a.is_coherent and not ctx.b.is_coherent:
        return ctx._better(section, True, intro, reason)
    if ctx.b.is_coherent and not ctx.a.is_coherent:
        return ctx._better(section, False, intro, reason)
    return None


def _criterion_fewer_unjustified(
    ctx: AnswerComparison, section: dict[str, Any]
) -> dict[str, Any] | None:
    """``answers.ss:848-857``."""
    intro = section.get("intro_all_in_all", "")
